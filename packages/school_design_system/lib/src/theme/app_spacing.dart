
abstract final class AppSpacing {
  AppSpacing._();

  // Extra small spacing
  static const double xs = 4;

  // Small spacing
  static const double sm = 8;

  // Medium spacing
  static const double md = 12;

  // Standard spacing
  static const double lg = 16;

  // Large spacing
  static const double xl = 20;

  // Extra large spacing
  static const double xxl = 24;

  // Larger section spacing
  static const double xxxl = 32;

  // Page layout spacing
  static const double pageHorizontal = 24;
  static const double pageVertical = 24;

  // Card spacing
  static const double cardPadding = 16;
  static const double cardGap = 12;

  // Form spacing
  static const double formFieldGap = 16;
  static const double formSectionGap = 24;

  // Button spacing
  static const double buttonHorizontal = 20;
  static const double buttonVertical = 12;

  // Common corner radii
  static const double radiusSmall = 6;
  static const double radiusMedium = 10;
  static const double radiusLarge = 12;
  static const double radiusExtraLarge = 16;

  // Icon sizes
  static const double iconSmall = 16;
  static const double iconMedium = 20;
  static const double iconLarge = 24;
  static const double iconExtraLarge = 32;

  // Common component heights
  static const double buttonHeight = 48;
  static const double inputHeight = 48;
  static const double appBarHeight = 56;
}
